/** normaliza espaços e alinha as linhas no mesmo comprimento */
function norm(art: string) {
  // Espaço comum aqui é SEMPRE lixo de copiar/colar, nunca conteúdo: removendo
  // (em vez de trocar por U+2800) as quatro artes fecham retangulares. Trocar
  // deixava COELHOS com linhas de 41 a 43 numa grade de 40 — a prova.
  const linhas = art.replace(/\r/g, "").split("\n").map((l) => l.replace(/ /g, ""));
  while (linhas.length && !linhas[0].replace(/⠀/g, "").trim()) linhas.shift();
  while (linhas.length && !linhas[linhas.length - 1].replace(/⠀/g, "").trim()) linhas.pop();
  const w = Math.max(...linhas.map((l) => l.length));
  return linhas.map((l) => l.padEnd(w, "⠀")).join("\n");
}

