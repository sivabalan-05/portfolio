/** Artes Braille recuperadas da versão editorial aprovada. */
function norm(art: string) {
  const linhas = art.replace(/\r/g, "").split("\n").map((line) => line.replace(/ /g, ""));
  while (linhas.length && !linhas[0].replace(/⠀/g, "").trim()) linhas.shift();
  while (linhas.length && !linhas[linhas.length - 1].replace(/⠀/g, "").trim()) linhas.pop();
  const width = Math.max(...linhas.map((line) => line.length));
  return linhas.map((line) => line.padEnd(width, "⠀")).join("\n");
}

