/** Braille engravings used for editorial ornaments and dividers. */
function norm(art: string) {
  const lines = art.replace(/\r/g, "").split("\n").map((line) => line.replace(/ /g, ""));
  while (lines.length && !lines[0].replace(/⠀/g, "").trim()) lines.shift();
  while (lines.length && !lines[lines.length - 1].replace(/⠀/g, "").trim()) lines.pop();
  const width = Math.max(...lines.map((line) => line.length));
  return lines.map((line) => line.padEnd(width, "⠀")).join("\n");
}

